import { beforeEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, screen, waitFor } from '@testing-library/react';
import { ApiError } from '../../api/client';
import { IntelligencePanel } from '../../components/ui/IntelligencePanel';
import { renderWithProviders } from '../../test/render';
import type { AiStatusResponse, InsightResponse } from '../../types/api';

vi.mock('../../api/ai', () => ({
  aiKeys: {
    status: () => ['ai', 'status'],
    insights: (id: number) => ['ai', 'insights', id],
  },
  getAiStatus: vi.fn(),
  postInsights: vi.fn(),
}));

const { getAiStatus, postInsights } = await import('../../api/ai');

const status: AiStatusResponse = {
  enabled: true,
  geminiConfigured: true,
  geminiAvailable: true,
  geminiModel: 'gemini-3.8-flash',
  ollamaConfigured: true,
  ollamaAvailable: false,
  ollamaModel: '',
  deterministicAvailable: true,
  defaultEngine: 'GEMINI',
  routing: 'GEMINI_THEN_RULE_BASED',
  routingReasons: ['OLLAMA_NOT_AVAILABLE'],
};

function report(overrides: Partial<InsightResponse> = {}): InsightResponse {
  return {
    batchId: 7,
    engine: 'GEMINI',
    engineModel: 'gemini-3.8-flash',
    fallbackReason: null,
    cached: false,
    measured: {
      rowsRead: 100, importedCount: 80, rejectedCount: 20,
      newCount: 70, changedCount: 5, unchangedCount: 5, errorCount: 22,
      importedPercentage: '80.0', rejectedPercentage: '20.0', errorsPerRejectedRow: '1.10',
      errorCountsByCode: {
        MISSING_REQUIRED: 5, INVALID_FORMAT: 4, OUT_OF_RANGE: 3, DUPLICATE_ID: 5, WRONG_FIELD_COUNT: 5,
      },
      schemaColumns: ['student_id', 'full_name'],
    },
    summary: 'Most rows imported cleanly; a fifth were rejected.',
    overallAssessment: 'Quality concerns are concentrated in identifier and format checks.',
    findings: [{
      title: 'Duplicate student identifiers', severity: 'HIGH',
      evidenceMetric: 'DUPLICATE_ID_COUNT', evidenceValue: '5',
      explanation: 'Five later occurrences of an existing identifier were rejected.',
      recommendedAction: 'De-duplicate the source export.',
    }],
    recommendedActions: ['De-duplicate the source export.'],
    limitations: 'Aggregate counters only.',
    advisoryOnly: true,
    ...overrides,
  };
}

beforeEach(() => {
  vi.mocked(getAiStatus).mockReset();
  vi.mocked(postInsights).mockReset();
  vi.mocked(getAiStatus).mockResolvedValue(status);
  vi.mocked(postInsights).mockResolvedValue(report());
});

describe('IntelligencePanel', () => {
  it('shows ClearGrade Intelligence identity and provider availability', async () => {
    renderWithProviders(<IntelligencePanel batchId={7} />);

    expect(screen.getByRole('heading', { name: 'ClearGrade Intelligence' })).toBeInTheDocument();
    expect(await screen.findByText(/gemini-3.8-flash/)).toBeInTheDocument();
    expect(screen.getByText(/Ollama:/)).toBeInTheDocument();
    expect(screen.getByText('Unavailable')).toBeInTheDocument();
    expect(screen.getByText(/Rule-based:/)).toBeInTheDocument();
    expect(screen.getByText('Always available')).toBeInTheDocument();
    expect(screen.getByText(/Routing: GEMINI_THEN_RULE_BASED/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Analyse import' })).toHaveAttribute(
      'aria-describedby', 'privacy-disclosure');
    expect(screen.getByText(/never student names, IDs, emails/)).toBeInTheDocument();
  });

  it('renders a Gemini report with separated facts, interpretation and advice', async () => {
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByText(/Generated by Gemini/)).toBeInTheDocument();
    expect(screen.getByText('Fresh analysis')).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Measured import quality' })).toBeInTheDocument();
    expect(screen.getByText('Measured by ClearGrade · never AI-generated')).toBeInTheDocument();
    expect(screen.getByText('80.0%')).toBeInTheDocument();
    expect(screen.getByText('Duplicate identifiers')).toBeInTheDocument();
    expect(screen.getByText('Evidence metric:')).toBeInTheDocument();
    expect(screen.getByText('DUPLICATE_ID_COUNT')).toBeInTheDocument();
    expect(screen.getByText('Exact value:').nextElementSibling).toHaveTextContent('5');
    expect(screen.getByRole('heading', { name: 'Interpretation' })).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Recommended actions' })).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Findings by severity' })).toBeInTheDocument();
    expect(screen.getByText(/Advisory only/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Run new analysis' })).toBeInTheDocument();
  });

  it('identifies Ollama as the engine that generated a fallback result', async () => {
    vi.mocked(postInsights).mockResolvedValue(report({
      engine: 'OLLAMA', engineModel: 'llama3.2', fallbackReason: 'GEMINI_UNAVAILABLE',
    }));
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByText(/Generated by Ollama/)).toBeInTheDocument();
    expect(screen.getByText(/gemini unavailable/)).toBeInTheDocument();
    expect(screen.queryByText(/Rule-based analysis — AI providers/)).not.toBeInTheDocument();
  });

  it('shows the exact rule-based message when both AI providers are unavailable', async () => {
    vi.mocked(postInsights).mockResolvedValue(report({
      engine: 'RULE_BASED', engineModel: 'deterministic-v1', fallbackReason: 'NO_AI_PROVIDERS_AVAILABLE',
    }));
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByText('Rule-based analysis — AI providers are currently unavailable.')).toBeInTheDocument();
    expect(screen.getByText(/Generated by Rule-based/)).toBeInTheDocument();
  });

  it('shows a cached analysis indicator', async () => {
    vi.mocked(postInsights).mockResolvedValue(report({ cached: true }));
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByText('Cached analysis')).toBeInTheDocument();
    expect(screen.queryByText('Fresh analysis')).not.toBeInTheDocument();
  });

  it('renders a loading state while analysis runs', async () => {
    vi.mocked(postInsights).mockImplementation(() => new Promise(() => {}));
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByText(/Analysing aggregate import metrics/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Analysing…' })).toBeDisabled();
  });

  it('shows a retry state without hiding import results', async () => {
    vi.mocked(postInsights).mockRejectedValueOnce(new ApiError(429, 'ANALYSIS_COOLDOWN', 'slow down'));
    renderWithProviders(<IntelligencePanel batchId={7} />);
    fireEvent.click(screen.getByRole('button', { name: 'Analyse import' }));

    expect(await screen.findByRole('alert')).toHaveTextContent(/wait a moment/i);
    fireEvent.click(screen.getByRole('button', { name: /Retry analysis/ }));
    await waitFor(() => expect(postInsights).toHaveBeenCalledTimes(2));
    expect(await screen.findByText(/Generated by Gemini/)).toBeInTheDocument();
  });

  it('degrades gracefully when provider status cannot be loaded', async () => {
    vi.mocked(getAiStatus).mockRejectedValue(new Error('offline'));
    renderWithProviders(<IntelligencePanel batchId={7} />);

    expect(await screen.findByText(/Provider status could not be checked/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Analyse import' })).toBeEnabled();
  });

  it('stays disabled for a non-completed batch', async () => {
    renderWithProviders(<IntelligencePanel batchId={7} disabled />);
    expect(screen.getByRole('button', { name: 'Analyse import' })).toBeDisabled();
    expect(await screen.findByText(/available when this import has completed/)).toBeInTheDocument();
    expect(postInsights).not.toHaveBeenCalled();
  });
});
